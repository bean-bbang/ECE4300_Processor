`timescale 1ns/1ps

module instruction_memory(
    input  wire [31:0] address,
    output reg  [31:0] instruction
);
    reg [31:0] mem [0:9];

    initial begin
        mem[0] = 32'b0000_0000_0000_0000_0000_0000_0000_0001; 
        mem[1] = 32'b0000_0000_0000_0000_0000_0000_0000_0010;
        mem[2] = 32'b0000_0000_0000_0000_0000_0000_0000_0011;  
        mem[3] = 32'b0000_0000_0000_0000_0000_0000_0000_0100;
        mem[4] = 32'b0000_0000_0000_0000_0000_0000_0000_0101;  
        mem[5] = 32'b0000_0000_0000_0000_0000_0000_0000_0110;
        mem[6] = 32'b0000_0000_0000_0000_0000_0000_0000_0111;  
        mem[7] = 32'b0000_0000_0000_0000_0000_0000_0000_1000;
        mem[8] = 32'b0000_0000_0000_0000_0000_0000_0000_1001;  
        mem[9] = 32'b0000_0000_0000_0000_0000_0000_0000_1010;
    end

    always @(*) begin
        if (address < 10) instruction = mem[address];
        else              instruction = 32'b0;
    end
    
endmodule